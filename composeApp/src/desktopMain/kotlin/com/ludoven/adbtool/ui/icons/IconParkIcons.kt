    private fun buildIconParkIcon(
        name: String,
        paths: List<IconParkPath>,
    ): ImageVector = ImageVector.Builder(
        name = "IconPark.$name",
        defaultWidth = 48.dp,
        defaultHeight = 48.dp,
        viewportWidth = 48f,
        viewportHeight = 48f
    ).apply {
        paths.forEach { path ->
            addPath(
                pathData = PathParser().parsePathString(path.data).toNodes(),
                fill = if (path.kind == IconParkPathKind.Fill) SolidColor(Color.Black) else null,
                stroke = if (path.kind == IconParkPathKind.Stroke) SolidColor(Color.Black) else null,
                strokeLineWidth = if (path.kind == IconParkPathKind.Stroke) path.strokeWidth else 0f,
                strokeLineCap = StrokeCap.Round,
                strokeLineJoin = StrokeJoin.Round
            )
        }
    }.build()

    private data class IconParkPath(
        val data: String,
        val kind: IconParkPathKind,
        val strokeWidth: Float = 4f
    )

    private enum class IconParkPathKind {
        Fill,
        Stroke
    }
